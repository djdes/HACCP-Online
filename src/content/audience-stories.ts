/**
 * «Подходит для» — типы заведений с конкретикой вместо чипов.
 *
 * Раньше здесь стоял ряд слов («Рестораны», «Кафе», «Пекарни»): он
 * говорил, кому продукт продают, но не говорил, что у этих людей
 * меняется. Каждая карточка теперь отвечает на один вопрос — что было
 * на бумаге и что стало.
 *
 * `photo` — путь к фотографии заведения в `public/landing/audience/`.
 * Пока null: снимков в проекте нет, а брать случайные стоковые в
 * коммерческий лендинг без проверенной лицензии нельзя. Пока `photo`
 * пустой, карточка рисует градиентную плашку с иконкой; чтобы
 * поставить фото, достаточно положить файл и вписать сюда путь —
 * вёрстка уже рассчитана на соотношение 4:3.
 */
export type AudienceStory = {
  id: string;
  title: string;
  icon: LucideIcon;
  photo: string | null;
  /// Короткий результат — то, что видно на карточке крупно.
  result: string;
  /// Насколько журнал ведётся сам. «auto» — человек не участвует
  /// (датчики и бот пишут за него), «semi» — участвует, но вместо
  /// заполнения от руки подтверждает подставленное.
  automation: "auto" | "semi";
  before: string;
  after: string;
};

