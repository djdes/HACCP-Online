/**
 * Отзывы заведений для секции «Что говорят заведения».
 *
 * ВАЖНО: массив намеренно пуст, и секция не отрисуется, пока в нём
 * ничего нет.
 *
 * Придуманные отзывы на боевом лендинге — это выдуманные отзывы от
 * несуществующих людей: их нельзя отличить от настоящих, и читатель
 * принимает решение о покупке, опираясь на них. Поэтому заготовок
 * «для красоты» здесь не будет — только реальные слова реальных
 * клиентов, с их разрешения.
 *
 * Как добавить настоящий отзыв:
 *   1. Получить письменное согласие клиента на публикацию имени,
 *      заведения и города.
 *   2. Добавить объект ниже и проставить `approved: true`.
 *   3. Секция появится на лендинге сама — правок вёрстки не нужно.
 */
export type Testimonial = {
  id: string;
  /// Текст отзыва — дословно, без редактуры «под маркетинг».
  quote: string;
  /// Имя как его разрешили опубликовать.
  author: string;
  /// Должность — «управляющая», «шеф-повар», «владелец».
  role: string;
  /// Заведение и город: «Кафе „Веранда“ · Казань».
  place: string;
  /// Оценка 1–5. Отсутствует — звёзды не рисуем.
  rating?: number;
  /// Страховка от случайной публикации черновика: без true не покажем.
  approved: boolean;
};

export const TESTIMONIALS: Testimonial[] = [];

/** Показываем секцию только с подтверждёнными отзывами. */
export const APPROVED_TESTIMONIALS = TESTIMONIALS.filter((t) => t.approved);
