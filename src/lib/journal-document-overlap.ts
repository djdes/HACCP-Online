/**
 * Есть ли уже документ на тот же период.
 *
 * Зачем: `/api/journal-documents` создавал документ безусловно.
 * Автосоздание ночью делает документ на период, потом руководитель
 * нажимает «Создать документ» — и на один и тот же период выходит два
 * бланка. На проде 2026-09-08 так и было: «Гигиенический журнал ·
 * Сентябрь с 1 по 15» и «Гигиенический журнал — 1–15 сентября 2026»,
 * разные названия из разных мест кода, один интервал.
 *
 * Для матричных журналов документ и ЕСТЬ период: два бланка на те же
 * даты означают, что половина отметок смены попала в один, половина в
 * другой, и на проверке ни один не выглядит заполненным.
 *
 * Отказывать наглухо нельзя — бывает, что второй документ нужен
 * осознанно. Поэтому функция только НАХОДИТ совпадение, а решение
 * («открыть существующий» или «всё равно создать») принимает человек.
 */

export type DocumentPeriod = {
  id: string;
  title: string;
  dateFrom: Date;
  dateTo: Date;
  status?: string | null;
};

/**
 * Пересекаются ли отрезки. Границы включительные: документ «1–15» и
 * документ «15–30» делят пятнадцатое число, и это уже перекрытие —
 * отметка за этот день попадёт в оба.
 */
export function periodsOverlap(
  a: { dateFrom: Date; dateTo: Date },
  b: { dateFrom: Date; dateTo: Date },
): boolean {
  return a.dateFrom.getTime() <= b.dateTo.getTime() &&
    b.dateFrom.getTime() <= a.dateTo.getTime();
}

/**
 * Первый активный документ, пересекающийся с новым периодом.
 *
 * Закрытые не мешают: закрытый документ — это уже сданный период, и
 * новый бланк рядом с ним нормален.
 */
export function findOverlappingDocument<T extends DocumentPeriod>(
  existing: T[],
  period: { dateFrom: Date; dateTo: Date },
): T | null {
  for (const doc of existing) {
    if (doc.status && doc.status !== "active") continue;
    if (periodsOverlap(doc, period)) return doc;
  }
  return null;
}
