/**
 * Заголовок H1 для страницы журнала `/journals-info/<code>`.
 *
 * Источников три, и порядок неслучаен.
 *
 * 1. `JOURNAL_SEO.title` — он написан «ключ первым» («Журнал списания
 *    продукции», «Журнал учёта стеклянной посуды») и потому ближе всего
 *    к тому, что человек набирает в поиске. Хвост после тире или
 *    двоеточия («— образец для общепита», «: как вести») в заголовок
 *    страницы не нужен: он уточняет сниппет, а не называет сущность.
 * 2. Название из каталога — годится, но у части журналов там не запрос,
 *    а канцелярская форма: `product_writeoff` называется «Акт
 *    забраковки», хотя ищут «журнал списания».
 * 3. `tagline` — последний рубеж. Именно он стоял в H1 раньше и давал
 *    заголовки вида «Акт списания продукции.» — описательное
 *    предложение с точкой, без слова «журнал».
 */
export function journalHeadline(
  seoTitle: string | undefined,
  catalogName: string | undefined,
  tagline: string
): string {
  const fromSeo = (seoTitle ?? "").trim();
  if (fromSeo) {
    // Режем по « — » и по «: », но не по дефису внутри слова
    // («Чек-лист») и не по двоеточию без пробела.
    const head = fromSeo.split(/\s+—\s+|:\s+/)[0].trim();
    if (head) return head.replace(/[.\s]+$/, "");
  }
  const fromCatalog = (catalogName ?? "").trim();
  if (fromCatalog) return fromCatalog.replace(/[.\s]+$/, "");
  return tagline.replace(/[.\s]+$/, "");
}
