/**
 * Название организации для показа человеку.
 *
 * Аккаунты, заведённые мгновенной регистрацией до правки генератора,
 * называются «Организация ivan@mail.ru» — почта попадала в шапку
 * кабинета, в селектор организаций и в PDF-выгрузки. Переименовывать их
 * в базе нельзя: человек мог сам так назвать компанию. Поэтому чиним на
 * отображении — до тех пор, пока он не заполнит анкету.
 */
const PLACEHOLDER = "Моя организация";

export function orgDisplayName(
  name: string | null | undefined,
  fallback = PLACEHOLDER,
): string {
  const value = (name ?? "").trim();
  if (!value) return fallback;
  // Технические названия вида «Организация <почта>» показываем
  // нейтрально: адрес в шапке выглядит как ошибка, а не как название.
  if (value.includes("@")) return fallback;
  return value;
}
