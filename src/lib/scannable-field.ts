/**
 * У какого поля формы уместна кнопка «сканировать».
 *
 * Сценарий: приёмка товара, двенадцать цифр номера партии, мокрые руки и
 * телефон в пакете. Набрать это без ошибки трудно, а ошибка в номере
 * партии — это прослеживаемость, то есть смысл журнала.
 *
 * Отдельной функцией под тестом, потому что кнопка не должна появляться
 * где попало. Сканер рядом с «Примечанием» или «Фамилией» — шум, а шум
 * в форме, которую заполняют пятнадцать раз в смену, дороже пользы.
 * Названия полей в тридцати пяти журналах разные и заранее неизвестны,
 * поэтому решаем по смыслу имени, а не по списку журналов.
 */

const SCANNABLE_HINTS = [
  "партии",
  "партия",
  "batch",
  "lot",
  "штрихкод",
  "штрих-код",
  "штрих код",
  "barcode",
  "серийн",
  "serial",
  "накладн",
  "ттн",
  // Ключи полей в шаблонах латинские, подписи — русские; ловить
  // надо оба написания. Латинское «upd» сюда сознательно не
  // добавлено: оно есть внутри `updatedAt`.
  "ttn",
  "упд",
  "маркиров",
  "честный знак",
  "datamatrix",
  "qr",
];

/** Имена, где цифры есть, но сканировать нечего. */
const NOT_SCANNABLE_HINTS = ["телефон", "phone", "инн", "квартир", "дом"];

export function isScannableField(field: {
  key?: string | null;
  label?: string | null;
}): boolean {
  const haystack = `${field.key ?? ""} ${field.label ?? ""}`.toLowerCase();
  if (!haystack.trim()) return false;
  if (NOT_SCANNABLE_HINTS.some((hint) => haystack.includes(hint))) return false;
  if (SCANNABLE_HINTS.some((hint) => haystack.includes(hint))) return true;
  // «Номер документа» сам по себе слишком общий, а вот «номер накладной»
  // уже пойман выше. Оставляем только явные совпадения.
  return false;
}
