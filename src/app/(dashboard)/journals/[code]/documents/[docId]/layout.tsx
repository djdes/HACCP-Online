/**
 * Страница документа на мобильном едет вбок ЦЕЛИКОМ.
 *
 * Заголовок, кнопки, шапка бланка, таблицы и легенда двигаются одним
 * листом — тянешь в любом месте. Крошки при этом остаются на месте:
 * они приколоты `sticky left-0` на самой странице.
 *
 * Скроллер обязан быть во всю ширину экрана: `-mx-4` гасит `px-4`
 * родителя, `w-screen` растягивает до краёв, внутренний `px-4` возвращает
 * поля. Иначе он оказывается узким окном внутри отступов, и таблица
 * уезжает за его край — выглядит обрезанной.
 *
 * Сама страница вбок не скроллится: у `body` стоит overflow-x: clip ради
 * full-bleed белой подложки раздела.
 */
export default function JournalDocumentLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return (
    <div className="max-sm:-mx-4 max-sm:w-screen max-sm:overflow-x-auto max-sm:px-4">
      {children}
    </div>
  );
}
