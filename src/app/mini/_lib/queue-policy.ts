/**
 * Что делать с записью из офлайн-очереди после попытки отправки.
 *
 * Вынесено отдельной чистой функцией, потому что цена ошибки здесь
 * несимметрична: удалить запись рано — потерять работу человека,
 * оставить лишний раз — всего лишь повторить попытку. Каждая ветка
 * ниже выбрана исходя из этого.
 */

export type SendOutcome =
  /** Сервер ответил. */
  | { kind: "http"; status: number }
  /** Промис fetch отклонён: сети нет или она отвалилась на полпути. */
  | { kind: "network" };

export type QueueDecision =
  /** Отправлено — из очереди убираем. */
  | { kind: "done" }
  /** Оставляем и попробуем позже. */
  | { kind: "retry" }
  /** Сервер отверг данные навсегда — показываем человеку, не молчим. */
  | { kind: "rejected" };

export function decideQueueOutcome(outcome: SendOutcome): QueueDecision {
  if (outcome.kind === "network") return { kind: "retry" };

  const { status } = outcome;

  // 2xx — запись создана. Сюда же попадает повтор с тем же ключом
  // идемпотентности: сервер отдаёт прежний ответ, а не создаёт вторую.
  if (status >= 200 && status < 300) return { kind: "done" };

  // 409 — «уже сохраняется»: тот же ключ прямо сейчас в работе. Убирать
  // из очереди НЕЛЬЗЯ. Обычно это наша же прошлая попытка, и запись
  // появится, но бывает и осиротевшая бронь от процесса, который умер, —
  // тогда запись не создалась вовсе. Оставляем и повторяем: если запись
  // есть, следующая попытка получит 2xx и мы уберём её тогда.
  if (status === 409) return { kind: "retry" };

  // 401/403 — сессия протухла или доступ отобрали. Данные при этом
  // целы: человек войдёт снова, и очередь доедет.
  if (status === 401 || status === 403) return { kind: "retry" };

  // 408/429 и всё 5xx — сервер сам просит подождать.
  if (status === 408 || status === 429 || status >= 500) return { kind: "retry" };

  // Остальные 4xx — данные не пройдут никогда, сколько ни повторяй
  // (не тот шаблон, не прошла валидация). Молча удалять нельзя: человек
  // считает запись сделанной.
  return { kind: "rejected" };
}

/**
 * Пауза перед следующей попыткой. Растёт, но упирается в потолок:
 * смена длится часы, и ждать между попытками полсмены бессмысленно.
 */
export function retryDelayMs(attempts: number): number {
  const base = 5_000 * 2 ** Math.max(0, attempts - 1);
  return Math.min(base, 5 * 60_000);
}
