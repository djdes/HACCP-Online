/**
 * Единые правила всплывающих окон — один канон на весь сайт.
 *
 * Что было не так на телефоне: карточка ограничивалась `vh`, а на iOS
 * Safari `100vh` — это ВЫСОКИЙ viewport (адресная строка спрятана).
 * Пока строка видна, окно выше экрана: у окна, прижатого к низу
 * (`bottom-3`), за верхний край уезжает шапка вместе с крестиком —
 * закрыть окно нечем. У окна по центру за края уходят и шапка, и кнопки.
 *
 * Правило:
 *
 *   1. Высота карточки — в `dvh` (динамический viewport, учитывает
 *      панели браузера). `vh` остаётся запасным для старых браузеров:
 *      `MODAL_CARD_HEIGHT_CLASS` объявляет обе величины.
 *   2. Карточка — `flex flex-col overflow-hidden`.
 *   3. Шапка с крестиком и подвал с кнопками — `shrink-0`: видны всегда.
 *   4. Скроллится СЕРЕДИНА (`MODAL_BODY_CLASS`), а не карточка целиком.
 *      `overscroll-contain` — чтобы прокрутка не уходила на страницу.
 *
 * Для простых диалогов без своей шапки/подвала (обычный
 * `<DialogContent>`) правило другое: карточка скроллится целиком, но
 * крестик закреплён «липкой» строкой и остаётся на виду — см.
 * `src/components/ui/dialog.tsx`.
 */

/** Максимальная высота карточки окна: 88% видимой части экрана. */
export const MODAL_CARD_HEIGHT_CLASS =
  "max-h-[88vh] supports-[height:100dvh]:max-h-[88dvh]";

/** То же, но для больших окон (гайды, «Что нового»): 90%. */
export const MODAL_CARD_HEIGHT_LG_CLASS =
  "max-h-[90vh] supports-[height:100dvh]:max-h-[90dvh]";

/** Карточка окна: колонка с закреплёнными шапкой и подвалом. */
export const MODAL_CARD_CLASS = `flex flex-col overflow-hidden ${MODAL_CARD_HEIGHT_CLASS}`;

/** Шапка и подвал — не сжимаются и не скроллятся. */
export const MODAL_STICKY_CLASS = "shrink-0";

/** Середина окна — единственное, что прокручивается. */
export const MODAL_BODY_CLASS = "min-h-0 flex-1 overflow-y-auto overscroll-contain";
